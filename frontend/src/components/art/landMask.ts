export interface MaskDot {
  /** cell center longitude, degrees */
  lon: number;
  /** cell center latitude, degrees */
  lat: number;
}

/** Iterate land cells as lon/lat pairs (cell centers). */
export function landDots(): MaskDot[] {
  const dots: MaskDot[] = [];
  for (let r = 0; r < LAND_MASK.length; r++) {
    const row = LAND_MASK[r];
    for (let c = 0; c < row.length; c++) {
      if (row[c] === '#') {
        dots.push({ lon: -180 + c * 5 + 2.5, lat: 90 - r * 5 - 2.5 });
      }
    }
  }
  return dots;
}
